-- 7. TRIGGER: update project_progress.updated_at
-- ==========================================
CREATE OR REPLACE FUNCTION update_progress_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_project_progress_updated ON project_progress;
CREATE TRIGGER trg_project_progress_updated
  BEFORE UPDATE ON project_progress
  FOR EACH ROW EXECUTE FUNCTION update_progress_timestamp();

