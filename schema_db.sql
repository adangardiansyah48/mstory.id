-- ==========================================
-- 2. ENUM TYPES CREATION
-- ==========================================
CREATE TYPE dp_type_enum AS ENUM ('PERCENTAGE', 'FIXED');
CREATE TYPE booking_status_type AS ENUM ('CONSULTATION', 'BOOKED', 'COMPLETED', 'CANCELLED');
CREATE TYPE location_type_enum AS ENUM ('KOTA_TASIK', 'LUAR_KOTA');
CREATE TYPE retouch_status_type AS ENUM ('PENDING', 'IN_PROGRESS', 'DONE');
CREATE TYPE printing_status_type AS ENUM ('NOT_STARTED', 'IN_PRINTING', 'READY_FOR_PICKUP', 'DELIVERED');
CREATE TYPE workflow_status_type AS ENUM ('SHOOTING', 'EDIT', 'PRINTING', 'READY', 'DELIVERED');

-- ==========================================
-- 3. TABLES SCHEMA DEFINITION
-- ==========================================

-- 3.1 Categories (Kategori Utama)
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    icon VARCHAR(64) DEFAULT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3.2 Sub Categories (Sub-Kategori Layanan)
CREATE TABLE sub_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES categories(id) ON DELETE CASCADE,
    name VARCHAR NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3.3 Packages (Daftar Paket Layanan + Dynamic DP Config)
CREATE TABLE packages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sub_category_id BIGINT REFERENCES sub_categories(id) ON DELETE CASCADE,
    name VARCHAR NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    duration_hours INT,
    crew_info TEXT,
    inclusions TEXT NOT NULL,
    dp_value DECIMAL(12, 2) DEFAULT 200000.00,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3.4 Addons (Layanan Tambahan)
CREATE TABLE addons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3.5 Clients (Data Pelanggan)
CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR NOT NULL,
    whatsapp_number VARCHAR NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3.6 Bookings (Transaksi Booking)
CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR UNIQUE NOT NULL,
    client_id BIGINT REFERENCES clients(id) ON DELETE CASCADE,
    event_date DATE NOT NULL,
    booking_date DATE DEFAULT CURRENT_DATE,
    location_type location_type_enum DEFAULT 'KOTA_TASIK',
    event_address TEXT NOT NULL,
    subtotal DECIMAL(12, 2) NOT NULL,
    transport_fee DECIMAL(12, 2) DEFAULT 0,
    grand_total DECIMAL(12, 2) NOT NULL,
    dp_amount DECIMAL(12, 2) NOT NULL,
    status booking_status_type DEFAULT 'CONSULTATION',
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    dp_paid_at TIMESTAMP WITH TIME ZONE DEFAULT NULL,
    paid_at TIMESTAMP WITH TIME ZONE DEFAULT NULL,
    source VARCHAR(20) DEFAULT 'CLIENT',
    vendor_name TEXT
);

-- 3.7 Booking Details (Detail Paket yang Dipilih)
CREATE TABLE booking_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES bookings(id) ON DELETE CASCADE,
    package_id BIGINT REFERENCES packages(id) ON DELETE RESTRICT,
    price_at_booking DECIMAL(12, 2) NOT NULL
);

-- 3.8 Booking Addons (Detail Add-ons yang Dipilih)
CREATE TABLE booking_addons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES bookings(id) ON DELETE CASCADE,
    addon_id BIGINT REFERENCES addons(id) ON DELETE RESTRICT,
    price_at_booking DECIMAL(12, 2) NOT NULL,
    qty INT DEFAULT 1
);

-- 3.9 Project Progress (Tracking SLA Editor & Cetak)
CREATE TABLE project_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT REFERENCES bookings(id) ON DELETE CASCADE UNIQUE,
    progress_status workflow_status_type DEFAULT 'SHOOTING',
    notes TEXT,
    drive_link TEXT,
    expected_date DATE,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

