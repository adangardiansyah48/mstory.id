    info_text TEXT DEFAULT 'Terima kasih telah meluangkan waktu menelusuri karya kami. Semoga langkah kita bisa bertemu, dan kami diberi kesempatan mengabadikan kisah Anda selanjutnya.',
    info_image TEXT,                          -- full public URL (folder website/info/, opsional)
    info_button_label TEXT DEFAULT 'Hubungi kami',

    -- Instagram Section
    instagram_handle TEXT DEFAULT 'mstory.id',
    instagram_url TEXT DEFAULT 'https://instagram.com/mstory.id',
    instagram_grid_count INT DEFAULT 4,       -- jumlah foto grid (2x2)

    -- Contact / CTA
    contact_heading TEXT DEFAULT 'Siap mengabadikan cerita Anda?',
    contact_text TEXT DEFAULT 'Konsultasi gratis — pilih paket, cek tanggal tersedia, lalu lanjut ke booking.',
    wa_number TEXT DEFAULT '6281234567890',
    wa_button_label TEXT DEFAULT 'WhatsApp Admin',
    booking_label TEXT DEFAULT 'Booking Online',
    booking_url TEXT DEFAULT '/?booking=true',

    -- Footer
    footer_copyright TEXT DEFAULT 'Hak cipta dilindungi',

    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

