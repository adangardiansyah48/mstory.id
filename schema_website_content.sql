    hero_duration_ms INT DEFAULT 3800,        -- durasi auto-slide (ms)

    -- Intro / About (#about)
    intro_heading TEXT DEFAULT 'Halo, kami Mstory.id',
    intro_text TEXT DEFAULT 'Kami percaya setiap momen layak dikenang bukan hanya apa adanya, tetapi bagaimana momen itu terasa. Lewat bidikan kamera, kami menghadirkan yang paling berharga — merawat tradisi dan bercerita tanpa kata. Di sini, kenangan diabadikan untuk selamanya.',

    -- Info Banner
