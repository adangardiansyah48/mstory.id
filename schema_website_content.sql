CREATE POLICY "website_gallery_admin_all"
    ON public.website_gallery_items
    FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- ==========================================
-- 3. Trigger: update updated_at otomatis
-- ==========================================
CREATE OR REPLACE FUNCTION update_website_timestamp()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_website_settings_updated ON public.website_settings;
CREATE TRIGGER trg_website_settings_updated
    BEFORE UPDATE ON public.website_settings
    FOR EACH ROW EXECUTE FUNCTION update_website_timestamp();

DROP TRIGGER IF EXISTS trg_website_gallery_updated ON public.website_gallery_items;
CREATE TRIGGER trg_website_gallery_updated
    BEFORE UPDATE ON public.website_gallery_items
    FOR EACH ROW EXECUTE FUNCTION update_website_timestamp();

